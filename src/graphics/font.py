_TURKISH = str.maketrans({"ı": "I", "İ": "I", "ş": "S", "Ş": "S", "ğ": "G", "Ğ": "G",
                          "ü": "U", "Ü": "U", "ö": "O", "Ö": "O", "ç": "C", "Ç": "C"})


def normalize_text(text: str) -> str:
    """Türkçe karakterleri ve küçük harfleri atlastaki karşılıklarına çevirir."""
    return text.translate(_TURKISH).upper()


def glyph_cell(ch: str) -> tuple[int, int]:
    code = ord(ch)
    if not FIRST_CHAR <= code <= LAST_CHAR or ch not in _GLYPHS:
        code = ord("?")
    i = code - FIRST_CHAR
    return i % COLUMNS, i // COLUMNS


def build_atlas() -> np.ndarray:
    """(H, W) uint8 atlas: 16 sütun x 6 satır, her hücre 6x8 piksel."""
    rows = (LAST_CHAR - FIRST_CHAR + COLUMNS) // COLUMNS
    atlas = np.zeros((rows * CELL_H, COLUMNS * CELL_W), dtype=np.uint8)
    for ch, pattern in _GLYPHS.items():
        cx, cy = glyph_cell(ch)
        for y, row in enumerate(pattern.split()):
            for x, bit in enumerate(row):
                if bit == "1":
                    atlas[cy * CELL_H + y, cx * CELL_W + x] = 255
    return atlas
